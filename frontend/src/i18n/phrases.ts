export type PhraseKey = keyof typeof P.en

export function t(key: PhraseKey, vars: Record<string, string | number> = {}, lang: Lang = getLang()): string {
  let s: string = (P[lang] as Record<string, string>)[key] ?? P.en[key]
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}
